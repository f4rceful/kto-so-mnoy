def region_from_dataset(region_type: str, region: str) -> str | None:
    if (region_type, region) in _SPECIAL_REGIONS:
        name = _SPECIAL_REGIONS[(region_type, region)]
    elif region_type == "Респ":
        name = f"{region} Республика" if region in _ADJECTIVE_REPUBLICS else f"Республика {region}"
    elif region_type == "обл":
        name = f"{region} область"
    elif region_type == "край":
        name = f"{region} край"
    elif region_type == "АО":
        name = f"{region} автономный округ"
    elif region_type == "г":
        name = region
    else:
        return None
    return name if name in REGIONS else None
